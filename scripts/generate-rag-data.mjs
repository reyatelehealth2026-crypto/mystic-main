#!/usr/bin/env node
// Pre-build step: inline the public/docs/* files used by the RAG retriever
// into a TS module so the worker bundle doesn't depend on the filesystem.
// Run automatically before `next build` (see package.json scripts).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const DOCS_DIR = path.join(ROOT, "public/docs");
const OUT = path.join(ROOT, "src/lib/rag/data.generated.ts");

const FILES = {
  kb: "mysticg_divination_KB_full_th.md",
  examples: "mysticg_examples_pack_th.md",
  kb_complete: "mysticflow-knowledge-complete.md",
  handbook: "mystical-knowledge-handbook.md",
  summary: "mysticflow_ai_knowledge_summary_th.md",
  esiimsi: "esiimsi_knowledge_th.md",
};

const entries = Object.entries(FILES).map(([key, file]) => {
  const full = path.join(DOCS_DIR, file);
  const content = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : "";
  if (!content) console.warn(`[rag] missing or empty: ${file}`);
  return { key, file, content };
});

const body = entries
  .map(({ key, file, content }) => {
    return `export const ${key}: RagFile = ${JSON.stringify({ file, content })} as const;`;
  })
  .join("\n\n");

const out = `// AUTO-GENERATED by scripts/generate-rag-data.mjs — do not edit by hand.
// Regenerated each build from public/docs/*.

export interface RagFile {
  file: string;
  content: string;
}

${body}

export const RAG_FILES = { ${entries.map((e) => e.key).join(", ")} } as const;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, "utf8");
console.log(`[rag] generated ${OUT} from ${entries.length} files`);
